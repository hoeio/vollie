# makes the embedded UD masks of kit r38 (patch 0012) from lab/c3/bench/udmask-<subj>.bin (tom-ud-kernels.md §0)
import base64, hashlib, struct, sys
R = sys.argv[1]
PICK = [(2, 4), (3, 12), (5, 20), (6, 28)]   # (token, layer): spread over depth and over the 8 decoded tokens
out = []
for s in ['yi15-6b', 'llama2-7b', 'deepseek7b']:
    b = open(f'{R}/lab/c3/bench/udmask-{s}.bin', 'rb').read()
    F, L, T = struct.unpack('<3i', b[:12]); assert F == 11008 and T == 8
    sha = hashlib.sha256(b).hexdigest()
    for t, l in PICK:
        m = t * L + l; o = 12 + m * 2 * F; row, inp = b[o:o + F], b[o + F:o + 2 * F]
        assert set(row) <= {0, 1} and set(inp) <= {0, 1}
        pk = lambda v: bytes(sum(v[i + j] << j for j in range(8)) for i in range(0, F, 8))
        blob = pk(row) + pk(inp)
        nb = [sum(inp[i:i + 32]) for i in range(0, F, 32)]
        print(f'{s} t={t} l={l} rows={sum(row)/F:.4f} in={sum(inp)/F:.4f} blk_min={min(nb)} blk_mean={sum(nb)/len(nb):.2f} blk_max={max(nb)} in_sub_row={all(r or not i for r, i in zip(row, inp))}', file=sys.stderr)
        out.append((s, t, l, sha[:16], base64.b64encode(blob).decode()))
print('// generated by mkmask.py (tom-r38-build.md) from lab/c3/bench/udmask-<subj>.bin: per mask 1376 B of gate row bits (|up| top 70 %)')
print('// then 1376 B of down input bits (ffn_vollie_ud != 0), bit i = byte i/8 bit i%8, base64')
print('struct UMaskSrc { const char * subj; int t, l; const char * file16; const char * b64; };')
print('const UMaskSrc UMASKS[12] = {')
for s, t, l, h, e in out:
    print(f'    {{ "{s}", {t}, {l}, "{h}",')
    for i in range(0, len(e), 120): print(f'      "{e[i:i+120]}"')
    print('    },')
print('};')
